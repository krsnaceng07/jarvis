"""src.agents.self_healing.strategies.tool_argument_repair — Autonomous parameter healing.

OpenClaw parity: mirrors prepareToolCallArguments and preflight coercion.
Repairs model syntax mistakes, path formatting, quote wrapping, parameter
aliases, and missing parent directories.
"""

from __future__ import annotations

import copy
import json
import re
from pathlib import Path
from typing import Any
import unicodedata

from ..failure_event import ErrorCategory, FailureEvent
from .base import RecoveryResult, RecoveryStrategy

#: Common argument aliases across LLM tool call hallucinations
PARAM_ALIASES: dict[str, dict[str, str]] = {
    "write": {
        "filepath": "path",
        "file_path": "path",
        "filename": "path",
        "file": "path",
        "text": "content",
        "data": "content",
        "body": "content",
    },
    "read": {
        "filepath": "path",
        "file_path": "path",
        "filename": "path",
        "file": "path",
        "target": "path",
    },
    "edit": {
        "old_text": "oldText",
        "new_text": "newText",
        "old": "oldText",
        "new": "newText",
        "filepath": "path",
        "file_path": "path",
        "filename": "path",
    },
    "mkdir": {
        "dir": "path",
        "directory": "path",
        "folder": "path",
        "dirpath": "path",
    },
    "ls": {
        "dir": "path",
        "directory": "path",
        "folder": "path",
    },
    "exec": {
        "cmd": "command",
        "script": "command",
        "run": "command",
    },
    "process": {
        "sessionId": "session_id",
        "name": "session_id",
        "process": "session_id",
        "proc": "session_id",
        "pid": "session_id",
        "app": "session_id",
    },
    "open_path": {
        "path": "target",
        "app": "target",
        "application": "target",
        "folder": "target",
        "dir": "target",
        "directory": "target",
    },
}


class ToolArgumentRepairStrategy(RecoveryStrategy):
    """Heuristically repairs malformed tool arguments generated by LLMs."""

    name: str = "tool_argument_repair"

    async def can_handle(self, event: FailureEvent) -> bool:
        """Handles tool validation errors, schema mismatches, and path I/O issues."""
        return event.category in (
            ErrorCategory.TOOL_VALIDATION_ERROR,
            ErrorCategory.SYSTEM_IO_ERROR,
            ErrorCategory.TOOL_EXECUTION_ERROR,
        )

    def repair_arguments(
        self,
        tool_name: str,
        args: dict[str, Any],
    ) -> tuple[dict[str, Any], list[str]]:
        """Perform heuristic repair transformations on tool arguments.

        Returns:
            (repaired_args, changes_made)
        """
        repaired = copy.deepcopy(args) if isinstance(args, dict) else {}
        changes: list[str] = []

        # 1. Alias Resolution
        tool_alias_map = PARAM_ALIASES.get(tool_name, {})
        for hallucinated_key, canonical_key in tool_alias_map.items():
            if hallucinated_key in repaired and canonical_key not in repaired:
                repaired[canonical_key] = repaired.pop(hallucinated_key)
                changes.append(f"Mapped alias '{hallucinated_key}' -> '{canonical_key}'")

        # 2. String unquoting & cleaning (quotes, backticks, whitespace)
        for k, v in list(repaired.items()):
            if isinstance(v, str):
                cleaned = unicodedata.normalize("NFC", v.strip())
                # Remove surrounding quotes: '"foo"' -> 'foo', "'foo'" -> 'foo'
                if (cleaned.startswith('"') and cleaned.endswith('"')) or (
                    cleaned.startswith("'") and cleaned.endswith("'")
                ):
                    cleaned = cleaned[1:-1].strip()
                    if cleaned != v:
                        repaired[k] = cleaned
                        changes.append(f"Stripped outer quotes from argument '{k}'")
                # Remove surrounding backticks: '`foo`' -> 'foo'
                elif cleaned.startswith("`") and cleaned.endswith("`"):
                    cleaned = cleaned[1:-1].strip()
                    if cleaned != v:
                        repaired[k] = cleaned
                        changes.append(f"Stripped backticks from argument '{k}'")
                elif cleaned != v:
                    repaired[k] = cleaned

                # If string looks like a JSON object or array, parse it
                if (cleaned.startswith("{") and cleaned.endswith("}")) or (
                    cleaned.startswith("[") and cleaned.endswith("]")
                ):
                    try:
                        parsed_json = json.loads(cleaned)
                        repaired[k] = parsed_json
                        changes.append(f"JSON-decoded string into structure for argument '{k}'")
                    except Exception:
                        pass

        # 3. Path Normalization (Windows / POSIX)
        if "path" in repaired and isinstance(repaired["path"], str):
            p_val = unicodedata.normalize("NFC", repaired["path"].strip())
            # Normalize redundant slashes or mixed slashes (safely eliminating double slashes)
            norm_p = re.sub(r"[/\\]+", "/", p_val)
            # Ensure drive root is clean: C:/ instead of C://
            norm_p = re.sub(r"^([a-zA-Z]):/+", r"\1:/", norm_p)
            # Remove trailing slash for files (if not root or directory tool)
            if tool_name in ("write", "edit", "read") and norm_p.endswith("/") and len(norm_p) > 3:
                norm_p = norm_p.rstrip("/")
                changes.append("Removed invalid trailing slash from file path")

            # Fix drive letter capitalization: c:/ -> C:/
            drive_match = re.match(r"^([a-zA-Z]):/(.*)$", norm_p)
            if drive_match:
                drive_letter = drive_match.group(1).upper()
                norm_p = f"{drive_letter}:/{drive_match.group(2)}"

            if norm_p != p_val:
                repaired["path"] = norm_p
                changes.append(f"Normalized path syntax: '{p_val}' -> '{norm_p}'")

        # 4. Auto-create parent directory on write
        if tool_name == "write" and "path" in repaired and isinstance(repaired["path"], str):
            try:
                target_path = Path(repaired["path"])
                parent_dir = target_path.parent
                if parent_dir and not parent_dir.exists():
                    parent_dir.mkdir(parents=True, exist_ok=True)
                    changes.append(f"Auto-created missing parent directory '{parent_dir}'")
            except Exception as dir_err:
                changes.append(f"Failed to auto-create parent dir: {dir_err}")

        # 5. Dual-case aliases for edit tool
        if tool_name == "edit":
            if "oldText" in repaired and "old_text" not in repaired:
                repaired["old_text"] = repaired["oldText"]
            elif "old_text" in repaired and "oldText" not in repaired:
                repaired["oldText"] = repaired["old_text"]
            if "newText" in repaired and "new_text" not in repaired:
                repaired["new_text"] = repaired["newText"]
            elif "new_text" in repaired and "newText" not in repaired:
                repaired["newText"] = repaired["new_text"]

        # 6. Target phrase cleaning for open_path
        if (
            tool_name == "open_path"
            and "target" in repaired
            and isinstance(repaired["target"], str)
        ):
            t_val = repaired["target"].strip()
            cleaned_t = re.sub(
                r"^(?:open|launch|start|run)\s+", "", t_val, flags=re.IGNORECASE
            ).strip()
            cleaned_t = re.sub(
                r"\s+on\s+(?:the\s+)?(?:pc|computer|windows|host)$",
                "",
                cleaned_t,
                flags=re.IGNORECASE,
            ).strip()
            cleaned_t = re.sub(r"\s+in\s+windows$", "", cleaned_t, flags=re.IGNORECASE).strip()
            if cleaned_t.lower() in ("notepad.py", "notepad.exe"):
                if not Path(cleaned_t).exists():
                    cleaned_t = "notepad"
                    changes.append("Heuristically repaired target 'notepad.py' to 'notepad'")
            if cleaned_t != t_val:
                repaired["target"] = cleaned_t
                changes.append(f"Cleaned target phrase: '{t_val}' -> '{cleaned_t}'")

        # 7. Dual alias sync for process tool
        if tool_name == "process":
            if "session_id" in repaired and "sessionId" not in repaired:
                repaired["sessionId"] = repaired["session_id"]
            elif "sessionId" in repaired and "session_id" not in repaired:
                repaired["session_id"] = repaired["sessionId"]

        # 8. PowerShell command resilience for exec (Remove-Item / Get-ChildItem / WScript / for-loops)
        if tool_name == "exec" and "command" in repaired and isinstance(repaired["command"], str):
            cmd = repaired["command"]
            new_cmd = cmd

            # If command attempts window minimization via WScript.Shell or SendKeys, convert to native COM Shell.Application.MinimizeAll()
            if re.search(r"wscript\.shell", new_cmd, re.IGNORECASE) and any(
                k in new_cmd.lower() for k in ("win+m", "win+d", "#m", "#d", "^{esc}", "minimize")
            ):
                new_cmd = "(New-Object -ComObject Shell.Application).MinimizeAll()"
                changes.append(
                    "Repaired window minimize to use native '(New-Object -ComObject Shell.Application).MinimizeAll()'"
                )
            # Fix missing variable before = New-Object -ComObject WScript.Shell
            elif re.search(
                r"(?:^|[;\s])=\s*New-Object\s+-ComObject\s+WScript\.Shell", new_cmd, re.IGNORECASE
            ):
                new_cmd = re.sub(
                    r"(^|[;\s])=\s*(New-Object\s+-ComObject\s+WScript\.Shell)",
                    r"\1$ws = \2",
                    new_cmd,
                    flags=re.IGNORECASE,
                )
                changes.append("Repaired missing variable '$ws' before '= New-Object'")

            # Fix malformed for-loop without loop variable (e.g. for(=0; -lt 50; ++))
            if re.search(
                r"\bfor\s*\(\s*=\s*0\s*;\s*-lt\s*(\d+)\s*;\s*\+\+\s*\)", new_cmd, re.IGNORECASE
            ):
                new_cmd = re.sub(
                    r"\bfor\s*\(\s*=\s*0\s*;\s*-lt\s*(\d+)\s*;\s*\+\+\s*\)",
                    r"for($i=0; $i -lt \1; $i++)",
                    new_cmd,
                    flags=re.IGNORECASE,
                )
                changes.append("Repaired missing loop variable in for-loop")

            # Fix bare .SendKeys without object reference
            if re.search(r"(?:^|[;\s{}])\.SendKeys\(", new_cmd, re.IGNORECASE):
                new_cmd = re.sub(
                    r"(^|[;\s{}])\.SendKeys\(",
                    r"\1$ws.SendKeys(",
                    new_cmd,
                    flags=re.IGNORECASE,
                )
                changes.append("Repaired bare .SendKeys with '$ws.SendKeys'")

            if "Remove-Item" in new_cmd or "remove-item" in new_cmd.lower():
                # 1) Ensure -Recurse is present (prevents NonInteractive prompts when folders have children)
                if not re.search(r"\b-(?:Recurse|r)\b", new_cmd, re.IGNORECASE):
                    new_cmd = re.sub(
                        r"\bRemove-Item\b", "Remove-Item -Recurse", new_cmd, flags=re.IGNORECASE
                    )
                    changes.append(
                        "Added -Recurse to Remove-Item to prevent non-interactive prompts"
                    )
                # 2) Ensure -Force is present
                if not re.search(r"\b-Force\b", new_cmd, re.IGNORECASE):
                    new_cmd = re.sub(
                        r"\bRemove-Item\b", "Remove-Item -Force", new_cmd, flags=re.IGNORECASE
                    )
                    changes.append("Added -Force to Remove-Item")
                # 3) Ensure -ErrorAction SilentlyContinue is present (prevents failure on in-use locked files)
                if not re.search(r"\b-ErrorAction\b", new_cmd, re.IGNORECASE) and not re.search(
                    r"\b-ea\b", new_cmd, re.IGNORECASE
                ):
                    new_cmd = re.sub(
                        r"\bRemove-Item\b",
                        "Remove-Item -ErrorAction SilentlyContinue",
                        new_cmd,
                        flags=re.IGNORECASE,
                    )
                    changes.append(
                        "Added -ErrorAction SilentlyContinue to Remove-Item to tolerate locked/temp files"
                    )

            # Check for Get-ChildItem in cleanup / temp pipelines
            if re.search(r"\bGet-ChildItem\b", new_cmd, re.IGNORECASE) and (
                "remove-item" in new_cmd.lower() or "temp" in new_cmd.lower()
            ):
                if not re.search(
                    r"Get-ChildItem[^\n|]+-ErrorAction", new_cmd, re.IGNORECASE
                ) and not re.search(r"Get-ChildItem[^\n|]+-ea\b", new_cmd, re.IGNORECASE):
                    new_cmd = re.sub(
                        r"\bGet-ChildItem\b",
                        "Get-ChildItem -ErrorAction SilentlyContinue",
                        new_cmd,
                        count=1,
                        flags=re.IGNORECASE,
                    )
                    changes.append("Added -ErrorAction SilentlyContinue to Get-ChildItem")

            if new_cmd != cmd:
                repaired["command"] = new_cmd

        # Browser action normalization (convert click/type/press to action="act")
        if tool_name == "browser":
            raw_action = repaired.get("action")
            if isinstance(raw_action, str) and raw_action.lower() in {
                "click",
                "clickcoords",
                "type",
                "press",
                "hover",
                "scrollintoview",
                "drag",
                "select",
                "fill",
                "resize",
                "wait",
                "evaluate",
            }:
                repaired["kind"] = raw_action.lower()
                repaired["action"] = "act"
                changes.append(
                    f"Normalized browser action '{raw_action}' -> action='act', kind='{raw_action.lower()}'"
                )

        return repaired, changes

    async def execute(self, event: FailureEvent) -> RecoveryResult:
        """Attempt autonomous repair on event context arguments."""
        tool_name = str(event.context.get("tool_name") or "")
        args = event.context.get("args") or {}

        if not tool_name or not isinstance(args, dict):
            return RecoveryResult(
                success=False,
                action_taken="No tool or arguments found to repair",
                error="Missing tool_name or args in failure context",
            )

        repaired_args, changes = self.repair_arguments(tool_name, args)

        if not changes:
            return RecoveryResult(
                success=False,
                action_taken="No heuristic repairs applicable",
                error="Arguments could not be repaired by standard heuristics",
            )

        return RecoveryResult(
            success=True,
            action_taken=f"Repaired arguments for '{tool_name}': {'; '.join(changes)}",
            repaired_args=repaired_args,
            requires_retry=True,
            details={"changes": changes, "repaired_args": repaired_args},
        )


