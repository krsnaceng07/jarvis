"""jarvis_llm — JARVIS's LLM client contracts, ported from OpenClaw.

OpenClaw parity: ``packages/llm-core/`` plus the ``StreamFn`` facade in
``src/llm/stream.ts``. This is Phase 5.7 of
``docs/OPENCLAW_BRAIN_PORT_PLAN_V2.md``.

This package is the foundation of the brain port and deliberately has
**no dependencies** beyond the standard library, mirroring
``packages/plugin_sdk``. Everything above it — the agent loop, sessions,
compaction, routing — imports these types and never redefines them.

The one contract to internalize
===============================
A provider (``StreamFn``) never raises. Failures are encoded in the
returned stream as an ``error`` event carrying an ``AssistantMessage``
whose ``stop_reason`` is ``"error"`` or ``"aborted"``. Wrap any provider
in :func:`guard_stream_fn` and that holds even when the provider
misbehaves. See ``stream.py`` for why every layer above depends on it.

Naming
======
Python-level names are ``snake_case``; the JSON wire format stays
``camelCase`` to remain byte-compatible with OpenClaw. ``None`` fields are
omitted from serialized payloads rather than emitted as ``null``, matching
TypeScript's ``undefined`` behaviour.
"""

