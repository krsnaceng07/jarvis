"""Public ``jarvis_agent`` surface: the OpenClaw agent-core port.

Port of ``packages/agent-core/src/index.ts``.

Names are re-exported explicitly rather than by ``import *``. OpenClaw uses
``export *`` because TypeScript resolves and checks it statically; in Python
a star import rebinds silently on collision. Four message dataclasses are
exported by both :mod:`.types` and :mod:`.messages` (the latter re-exports
them, so they are the same objects) — listing names explicitly is what makes
that verifiable rather than assumed.

Phase 5.8 covered the foundation modules; Phase 5.9 added the agent loop
(``agent_loop.py``); Phase 5.10 added compaction and branch
summarization; Phase 5.11 adds the ``Agent`` class. Turn-interruption
helpers stay out of this barrel on purpose, matching upstream.
"""

